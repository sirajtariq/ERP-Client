let nextInvoiceNum = 8;

export const customerService = {
  getAll: () => [...customersMock],

  getById: (id) => customersMock.find((c) => c.id === id) || null,

  create: (data) => {
    const invoiceNum = String(nextInvoiceNum).padStart(4, "0");
    nextInvoiceNum++;
    const newCustomer = {
      ...data,
      id: "cust_" + Date.now(),
      invoiceNo: `C-${invoiceNum}`,
      createdAt: new Date().toISOString().split("T")[0],
      summary: {
        creditSales: 0, cashReturns: 0, advanceApplied: 0, totalCollected: 0,
        cashReceived: 0, advanceAppliedBreakdown: 0, remainingBalance: data.openingCredit || 0,
        totalInvoices: 0, availableAdvance: 0, closingBalance: data.openingCredit || 0,
        openingAdvance: 0, advanceDeposits: 0, closingAvailableAdvance: 0,
      },
      transactions: [
        { id: "t1", date: "-", voucher: "OPENING", description: "Opening Balance", debit: data.openingCredit || null, credit: null, balance: data.openingCredit || 0, type: "Dr" },
      ],
    };
    customersMock.push(newCustomer);
    return newCustomer;
  },

  update: (id, data) => {
    const index = customersMock.findIndex((c) => c.id === id);
    if (index === -1) throw new Error("Customer not found");
    customersMock[index] = { ...customersMock[index], ...data };
    return customersMock[index];
  },

  delete: (id) => {
    const index = customersMock.findIndex((c) => c.id === id);
    if (index === -1) throw new Error("Customer not found");
    customersMock = customersMock.filter((c) => c.id !== id);
    return true;
  },
};
